#!/usr/bin/env node
/**
 * Copies the backend's brag template into the app, so the app's brag video is
 * drawn by exactly the same file the website's is.
 *
 *   node scripts/sync-brag-template.js
 *
 * Run it again whenever backend/app/services/brag_template.html changes.
 */

const fs = require('fs');
const path = require('path');

const source = path.resolve(__dirname, '../../../../backend/app/services/brag_template.html');
const target = path.resolve(__dirname, '../src/lib/brag/template.ts');

const html = fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
if (!html.includes('__SPEC__')) throw new Error(`${source} has no __SPEC__ placeholder.`);

fs.writeFileSync(
  target,
  `/**
 * GENERATED by scripts/sync-brag-template.js — do not edit.
 * Source: backend/app/services/brag_template.html
 */

export const BRAG_TEMPLATE = ${JSON.stringify(html)};
`,
);
console.log(`Wrote ${path.relative(process.cwd(), target)} (${html.length} characters).`);
